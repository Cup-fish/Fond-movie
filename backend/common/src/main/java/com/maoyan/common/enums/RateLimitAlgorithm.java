package com.maoyan.common.enums;

/**
 * 限流算法枚举
 *
 * <h3>算法对比（面试高频）：</h3>
 * <pre>
 * ┌─────────────────────┬──────────────────────────────────────┐
 * │ 滑动窗口             │ 令牌桶                               │
 * ├─────────────────────┼──────────────────────────────────────┤
 * │ 精确统计窗口内请求数  │ 按固定速率生成令牌，允许突发           │
 * │ 适合: 通用 API 限流   │ 适合: 秒杀/抢座等突发流量场景          │
 * │ 窗口边界可能有突刺    │ 天然支持突发 + 平滑限速               │
 * │ 实现: Redis ZSET      │ 实现: Redis String + Lua 原子操作     │
 * └─────────────────────┴──────────────────────────────────────┘
 * </pre>
 */
public enum RateLimitAlgorithm {

    /**
     * 滑动窗口算法 — 基于 Redis ZSET
     * <p>精确计数窗口内请求数，适合通用 API 限流</p>
     */
    SLIDING_WINDOW,

    /**
     * 令牌桶算法 — 基于 Redis String + Lua
     * <p>按固定速率补充令牌，允许突发消耗，适合抢座/秒杀场景</p>
     */
    TOKEN_BUCKET
}
